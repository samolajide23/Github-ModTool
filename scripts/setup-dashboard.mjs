/**
 * One-shot setup: upload app, upgrade install, poll for dashboard post, write fallback id.
 * Usage: npm run setup-dashboard
 */
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const OUT = join(ROOT, 'src/core/dashboard-post-id.generated.ts');
const SUBREDDIT = 'queue_toolk_dev';
const TITLE = 'QueueIQ — Prioritized mod queue';

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const loadToken = () => {
  const raw = readFileSync(join(homedir(), '.devvit', 'token'), 'utf8');
  let token = JSON.parse(raw).token;
  try {
    token = JSON.parse(Buffer.from(token, 'base64').toString()).accessToken || token;
  } catch {
    /* */
  }
  return token;
};

const redditGet = async (token, path) => {
  const response = await fetch(`https://oauth.reddit.com${path}`, {
    headers: {
      Authorization: `Bearer ${token}`,
      'User-Agent': 'queueiq-setup-dashboard/1.0',
    },
  });
  return response.json();
};

const findDashboardPost = async (token) => {
  const paths = [
    `/r/${SUBREDDIT}/search?q=${encodeURIComponent('QueueIQ')}&restrict_sr=1&sort=new&limit=50&raw_json=1`,
    `/r/${SUBREDDIT}/new?limit=100&raw_json=1`,
    `/user/queue-toolk/submitted?limit=50&raw_json=1`,
  ];
  for (const path of paths) {
    const json = await redditGet(token, path);
    for (const child of json?.data?.children ?? []) {
      const d = child.data;
      if (d?.title === TITLE || d?.title?.includes('QueueIQ')) {
        return d.name;
      }
    }
  }
  return null;
};

const writeGenerated = (postId) => {
  writeFileSync(
    OUT,
    `/** Auto-generated by npm run setup-dashboard */\nexport const FALLBACK_DASHBOARD_POST_ID: string | undefined = ${postId ? `"${postId}"` : 'undefined'};\n`,
    'utf8'
  );
};

const main = async () => {
  console.log('1/4 Building and uploading...');
  execSync('npm run build', { cwd: ROOT, stdio: 'inherit' });
  execSync('npx devvit upload', { cwd: ROOT, stdio: 'inherit' });

  const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
  const version = pkg.version === '0.0.0' ? null : pkg.version;
  const versionFlag = version ? `@${version}` : '@latest';

  console.log(`2/4 Upgrading install on r/${SUBREDDIT}...`);
  try {
    execSync(`npx devvit install ${SUBREDDIT} queue-toolk${versionFlag}`, {
      cwd: ROOT,
      stdio: 'inherit',
    });
  } catch {
    execSync(`npx devvit install ${SUBREDDIT} queue-toolk@latest`, {
      cwd: ROOT,
      stdio: 'inherit',
    });
  }

  console.log('3/4 Waiting for dashboard post (onAppUpgrade)...');
  const token = loadToken();
  let postId = null;
  for (let i = 0; i < 12; i++) {
    await sleep(5000);
    postId = await findDashboardPost(token);
    if (postId) break;
    console.log(`   … not found yet (${(i + 1) * 5}s)`);
  }

  if (postId) {
    writeGenerated(postId);
    console.log(`4/4 Done. Dashboard post: ${postId}`);
    console.log(`   https://www.reddit.com/r/${SUBREDDIT}/comments/${postId.replace(/^t3_/, '')}/`);
    console.log('   Restart npm run dev, then Open QueueIQ dashboard in playtest.');
    return;
  }

  writeGenerated(undefined);
  console.log('4/4 No dashboard post created automatically.');
  console.log('');
  console.log('One manual step (30 seconds):');
  console.log(`   Open https://www.reddit.com/r/${SUBREDDIT}/ (NOT the playtest URL)`);
  console.log('   Mod tools → Open QueueIQ dashboard');
  console.log('   Then run: npm run register-dashboard');
};

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
