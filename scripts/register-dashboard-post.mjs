/**
 * Finds an existing QueueIQ dashboard post via OAuth and writes the fallback id file.
 * Usage: npm run register-dashboard [-- URL]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = join(__dirname, '../src/core/dashboard-post-id.generated.ts');
const SUBREDDIT = 'queue_toolk_dev';
const TITLE = 'QueueIQ — Prioritized mod queue';
const APP_USER = 'queue-toolk';

const loadToken = () => {
  const raw = readFileSync(join(homedir(), '.devvit', 'token'), 'utf8');
  const { token } = JSON.parse(raw);
  try {
    const inner = JSON.parse(Buffer.from(token, 'base64').toString('utf8'));
    if (inner.accessToken) return inner.accessToken;
  } catch {
    /* bare token */
  }
  return token;
};

const redditGet = async (token, path) => {
  const response = await fetch(`https://oauth.reddit.com${path}`, {
    headers: {
      Authorization: `Bearer ${token}`,
      'User-Agent': 'queueiq-register-dashboard/1.0',
    },
  });
  const json = await response.json();
  if (!response.ok) {
    throw new Error(`${path} failed: ${JSON.stringify(json)}`);
  }
  return json;
};

const parsePostIdFromUrl = (url) => {
  const match = url.match(/\/comments\/([a-z0-9]+)\//i);
  if (!match) return null;
  return `t3_${match[1]}`;
};

const writeGenerated = (postId) => {
  const file = `/** Auto-generated by npm run register-dashboard — do not edit by hand */
export const FALLBACK_DASHBOARD_POST_ID: string | undefined = ${postId ? `"${postId}"` : 'undefined'};
`;
  writeFileSync(OUT, file, 'utf8');
  console.log(`Wrote ${OUT}`);
  console.log(`  FALLBACK_DASHBOARD_POST_ID = ${postId ?? 'undefined'}`);
};

const pickDashboardId = (children) => {
  for (const child of children) {
    const d = child.data;
    if (d?.title === TITLE || d?.title?.includes('QueueIQ')) {
      return d.name;
    }
  }
  return null;
};

const findBySearch = async (token) => {
  const q = encodeURIComponent('QueueIQ');
  const json = await redditGet(
    token,
    `/r/${SUBREDDIT}/search?q=${q}&restrict_sr=1&sort=new&limit=50&raw_json=1`
  );
  return pickDashboardId(json?.data?.children ?? []);
};

const findInNew = async (token) => {
  const json = await redditGet(token, `/r/${SUBREDDIT}/new?limit=100&raw_json=1`);
  return pickDashboardId(json?.data?.children ?? []);
};

const findByAppUser = async (token) => {
  const json = await redditGet(
    token,
    `/user/${APP_USER}/submitted?sort=new&limit=100&raw_json=1`
  );
  return pickDashboardId(json?.data?.children ?? []);
};

const main = async () => {
  const urlArg = process.argv[2];
  if (urlArg) {
    const postId = parsePostIdFromUrl(urlArg);
    if (!postId) throw new Error('Could not parse post id from URL');
    writeGenerated(postId);
    return;
  }

  const token = loadToken();
  console.log(`Searching for dashboard post in r/${SUBREDDIT}...`);

  const postId =
    (await findBySearch(token)) ??
    (await findInNew(token)) ??
    (await findByAppUser(token));

  if (postId) {
    console.log(`Found: ${postId}`);
    writeGenerated(postId);
    return;
  }

  writeGenerated(undefined);
  console.warn('No dashboard post found.');
  process.exit(1);
};

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
